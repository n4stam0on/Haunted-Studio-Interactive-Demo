#!/usr/bin/env python3
"""
Build step: turn the JSON source files into browser scripts.

    data/cases.json  ->  js/cases.js   (window.CASES)
    data/rules.json  ->  js/rules.js   (window.RULES)

Loading data as plain <script> files (instead of fetch) keeps the game
working when index.html is opened straight from disk, with no web server.
It also validates every case so a typo is caught before it reaches players.

Usage:
    python tools/build_cases.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQUIRED = {"id", "file", "title", "diff", "teaser", "s1", "s2", "s3", "s4", "reveal"}


def validate(cases, rules):
    problems = []
    ids = set()
    for c in cases:
        name = c.get("id", "?")
        missing = REQUIRED - c.keys()
        if missing:
            problems.append(f"{name}: missing {sorted(missing)}")
            continue
        if name in ids:
            problems.append(f"{name}: duplicate id")
        ids.add(name)
        if c["diff"] not in ("Easy", "Medium", "Hard"):
            problems.append(f"{name}: difficulty must be Easy, Medium, or Hard")
        if sum(o["v"] == "best" for o in c["s1"]["opts"]) != 1:
            problems.append(f"{name}: Station 1 needs exactly one best answer")
        if not any(f["r"] for f in c["s1"]["flags"]):
            problems.append(f"{name}: Station 1 needs at least one real red flag")
        width = len(c["s2"]["cols"])
        for i, row in enumerate(c["s2"]["rows"]):
            if len(row["c"]) != width:
                problems.append(f"{name}: log row {i} has {len(row['c'])} cells, expected {width}")
        if sum(a["g"] == "now" for a in c["s3"]["acts"]) != 3:
            problems.append(f"{name}: Station 3 needs exactly three 'now' moves")
        if sum(o["best"] for o in c["s4"]["opts"]) != 1:
            problems.append(f"{name}: Station 4 needs exactly one best summary")
    rule_ids = [r["id"] for r in rules["rules"]]
    if len(rule_ids) != len(set(rule_ids)):
        problems.append("rules: duplicate rule id")
    return problems


def main():
    cases = json.loads((ROOT / "data/cases.json").read_text(encoding="utf-8"))
    rules = json.loads((ROOT / "data/rules.json").read_text(encoding="utf-8"))
    problems = validate(cases, rules)
    if problems:
        raise SystemExit("Build stopped:\n  " + "\n  ".join(problems))
    header = "/* Generated by tools/build_cases.py from {src}. Edit the JSON, not this file. */\n"
    (ROOT / "js/cases.js").write_text(
        header.format(src="data/cases.json") + "window.CASES = " + json.dumps(cases, ensure_ascii=False) + ";\n", encoding="utf-8")
    (ROOT / "js/rules.js").write_text(
        header.format(src="data/rules.json") + "window.RULES = " + json.dumps(rules, ensure_ascii=False) + ";\n", encoding="utf-8")
    print(f"Built js/cases.js ({len(cases)} cases) and js/rules.js ({len(rules['rules'])} rules). All checks passed.")


if __name__ == "__main__":
    main()
